// ---------- Simple shuffle function (swaps random items one by one) ----------
function shuffle(array) {

  for (let i = array.length - 1; i > 0; i--) {

    let randomIndex = Math.floor(Math.random() * (i + 1));

    // swap array[i] and array[randomIndex]
    let temp = array[i];
    array[i] = array[randomIndex];
    array[randomIndex] = temp;

  }

  return array;

}

// ---------- Pick 20 random, non-repeating questions for the quiz ----------
function pickQuestions(catKey) {

  let allQuestionsInCategory = questionBank[catKey];
  let already = usedQuestions[catKey];

  // collect questions that have not been used yet
  let freshQuestions = [];

  for (let i = 0; i < allQuestionsInCategory.length; i++) {

    let q = allQuestionsInCategory[i];
    let isUsed = already.indexOf(q.question) !== -1;

    if (!isUsed) {
      freshQuestions.push(q);
    }

  }

  // if not enough fresh questions are left, reset and use all questions again
  if (freshQuestions.length < QUESTIONS_PER_QUIZ) {
    usedQuestions[catKey] = [];
    freshQuestions = allQuestionsInCategory.slice();
  }

  shuffle(freshQuestions);

  let selected = freshQuestions.slice(0, QUESTIONS_PER_QUIZ);

  // mark these questions as used
  for (let i = 0; i < selected.length; i++) {
    usedQuestions[catKey].push(selected[i].question);
  }

  return selected;

}

//  Build the category selection screen 
function buildCategoryScreen() {

  categoryGrid.innerHTML = "";

  for (let i = 0; i < categoryInfo.length; i++) {

    let cat = categoryInfo[i];
    let totalQuestions = questionBank[cat.key].length;

    let card = document.createElement("div");
    card.classList.add("category-card");

    card.innerHTML =
      '<span class="category-icon">' + cat.icon + '</span>' +
      '<div class="category-info">' +
        '<span class="category-name">' + cat.name + '</span>' +
        '<span class="category-count">' + totalQuestions + ' Questions</span>' +
      '</div>';

    card.onclick = function () {
      startQuizWithCategory(cat.key, cat.name);
    };

    categoryGrid.appendChild(card);

  }

}

