// ---------- Start quiz for the chosen category ----------
function startQuizWithCategory(catKey, catName) {

  currentCategoryKey = catKey;
  currentCategoryName = catName;
  currentQuestion = 0;
  score = 0;

  quizQuestions = pickQuestions(catKey);

  categoryScreen.classList.add("hidden");
  quizScreen.classList.remove("hidden");

  loadQuestion();

}

//  Load current question on screen 
function loadQuestion() {

  selectedAnswer = -1;
  nextBtn.disabled = true;

  let current = quizQuestions[currentQuestion];

  welcomeText.innerHTML = "Welcome, " + playerName + " 👋";

  progress.innerHTML = "Question " + (currentQuestion + 1) + " / " + quizQuestions.length;

  progressFill.style.width = ((currentQuestion + 1) / quizQuestions.length) * 100 + "%";

  categoryTag.innerHTML = currentCategoryName;

  question.innerHTML = current.question;

  options.innerHTML = "";

  for (let i = 0; i < current.options.length; i++) {

    let option = document.createElement("div");

    option.classList.add("option");

    option.innerHTML = current.options[i];

    option.onclick = function () {

      let allOptions = document.querySelectorAll(".option");

      for (let j = 0; j < allOptions.length; j++) {
        allOptions[j].classList.remove("selected");
      }

      option.classList.add("selected");

      selectedAnswer = i;

      nextBtn.disabled = false;

    };

    options.appendChild(option);

  }

}

//  Next button: check answer and move forward 
nextBtn.addEventListener("click", function () {

  if (selectedAnswer == quizQuestions[currentQuestion].answer) {
    score++;
  }

  currentQuestion++;

  if (currentQuestion < quizQuestions.length) {
    loadQuestion();
  } else {
    showResult();
  }

});

//  Show final result screen 
function showResult() {

  quizScreen.classList.add("hidden");
  resultScreen.classList.remove("hidden");

  let percentage = (score / quizQuestions.length) * 100;

  if (percentage >= 90) {
    finalMessage.innerHTML = "🏆 Excellent, " + playerName + "!";
  }
  else if (percentage >= 70) {
    finalMessage.innerHTML = "🌟 Great Job, " + playerName + "!";
  }
  else if (percentage >= 50) {
    finalMessage.innerHTML = "👍 Good Try, " + playerName + "!";
  }
  else {
    finalMessage.innerHTML = "📚 Keep Practicing, " + playerName + "!";
  }

  finalScore.innerHTML = currentCategoryName + " Score: " + score + " / " + quizQuestions.length;

  //  remember best score per category
  let storageKey = "brainboost_best_" + currentCategoryKey;
  let savedBest = localStorage.getItem(storageKey);
  let bestScore = savedBest ? parseInt(savedBest) : 0;

  if (score > bestScore) {
    bestScore = score;
    localStorage.setItem(storageKey, bestScore);
  }

  bestScoreText.innerHTML = "⭐ Best Score in " + currentCategoryName + ": " + bestScore + " / " + quizQuestions.length;

}

